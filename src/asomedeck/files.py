def language_for(path: str) -> str:
    name = os.path.basename(path).lower()
    if name in LANGUAGE_BY_NAME:
        return LANGUAGE_BY_NAME[name]
    # ".env.local" and "Dockerfile.dev" are a named file with a suffix saying which copy
    # of it this is, and splitext hands back (".env", ".local") -- so neither lookup
    # above hits. Asking the extension before the stem is the load-bearing part: the
    # other way round, "makefile.py" would come out as shell.
    stem, ext = os.path.splitext(name)
    if ext in LANGUAGES:
        return LANGUAGES[ext]
    return LANGUAGE_BY_NAME.get(stem, "plain")
