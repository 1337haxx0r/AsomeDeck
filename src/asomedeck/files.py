"""Reading a deck's files, and writing them back unchanged except where edited.

Everything here is pure and headless: listing a directory, deciding whether a file is
text, and turning bytes into a string and back. The widgets on top (``ui/file_tree.py``,
``ui/editor.py``) do no decoding of their own, so the round trip is testable without a
QApplication -- and it has to be, because the one unforgivable bug in an editor is
writing a file back with changes nobody asked for.

Three such changes are the *default* behaviour of ``open()`` and are prevented here:

* ``open(path).read()`` decodes with the locale encoding, which on Windows is cp1252. A
  UTF-8 file with an accented word in a comment comes back mojibake and is saved
  corrupted.
* Text mode translates newlines. A LF file read and written on Windows gains a CR on
  every line -- a whole-file diff produced by opening it and pressing save.
* A UTF-8 BOM is not part of the text. Decoded as plain ``utf-8`` it becomes a
  zero-width character at offset 0; written back without it the file loses a marker
  other tools may key on.

So a load carries its encoding and its newline through to the save, and
``tests/test_files.py`` pins that loading a file and saving it unedited produces
byte-identical output.

The one deliberate exception is a file with *mixed* line endings: the buffer holds LF
and the save re-expands to whichever ending was in the majority, so the mixture is
normalised. That is a change, it is stated rather than hidden, and a test asserts it --
the alternative is tracking endings per line, which no editor the user has does either.
"""

from __future__ import annotations

import codecs
import logging
import os
from dataclasses import dataclass

log = logging.getLogger(__name__)

#: Directories omitted when listing. Each is machine-generated and big enough that
#: showing it buries the deck inside its own build output.
#:
#: Deliberately short. Hiding a directory somebody actually wrote is a worse failure than
#: showing one they do not care about, so the ambiguous names -- ``dist``, ``build``,
#: ``target``, ``out`` -- are *not* here: they are generated in some decks and hand
#: written in others, and the tree cannot tell which.
HIDDEN_DIRS = frozenset({
    ".git", "__pycache__", "node_modules", ".venv", "venv",
    ".mypy_cache", ".pytest_cache", ".ruff_cache", ".tox",
})

#: Directory name suffixes hidden for the same reason. ``.egg-info`` is regenerated by
#: every editable install, which is exactly why this repository gitignores its own.
HIDDEN_DIR_SUFFIXES = (".egg-info",)

#: Refuse to open anything larger. The editor loads the whole file into a QTextDocument,
#: which for a 50 MB log means a multi-second freeze and several hundred MB of layout --
#: a terminal running ``less`` is the right tool and is one pane away.
MAX_BYTES = 2 * 1024 * 1024

#: How much of a file is inspected to decide whether it is text at all.
SNIFF_BYTES = 8192

#: Results of :func:`classify`.
TEXT = "text"
BINARY = "binary"
TOO_BIG = "too_big"
MISSING = "missing"


@dataclass(frozen=True, slots=True)
class Entry:
    """One row of a directory listing."""

    name: str
    path: str
    is_dir: bool


def hidden(name: str) -> bool:
    """Whether a *directory* of this name is omitted from listings."""
    return name in HIDDEN_DIRS or name.endswith(HIDDEN_DIR_SUFFIXES)


def list_dir(path: str) -> list[Entry]:
    """Directories first, then files, each case-insensitively by name.

    An unreadable directory lists as empty rather than raising. A tree walks into
    whatever the user points it at, including junctions onto other volumes and paths
    that stopped existing between the scan and the click, and none of that deserves a
    traceback.
    """
    try:
        with os.scandir(path) as scan:
            entries = list(scan)
    except OSError as exc:
        log.debug("cannot list %s: %s", path, exc)
        return []

    rows: list[Entry] = []
    for entry in entries:
        try:
            # follow_symlinks=False: a junction pointing at its own ancestor is a loop,
            # and the tree is lazy enough to walk into it forever.
            is_dir = entry.is_dir(follow_symlinks=False)
        except OSError:
            is_dir = False
        if is_dir and hidden(entry.name):
            continue
        rows.append(Entry(entry.name, os.path.join(path, entry.name), is_dir))
    rows.sort(key=lambda row: (not row.is_dir, row.name.lower()))
    return rows


#: How many files a deck walk will return before it stops looking.
#:
#: There is no useful answer to "which of these 40,000 files did you mean" typed into a
#: search box, and a palette that takes a second to open is not a palette. Breadth-first
#: below spends the budget where it is worth most: a repository's own files are near the
#: top, and what gets dropped when the cap bites is the deepest generated output --
#: which is the same thing HIDDEN_DIRS is already trying to keep out of sight.
WALK_LIMIT = 4000


def walk(root: str, limit: int = WALK_LIMIT) -> list[str]:
    """Every file under ``root``, breadth-first, up to ``limit``.

    Breadth-first and not ``os.walk``: depth-first spends the whole budget inside the
    first subdirectory it enters, so a capped depth-first walk of a repository can return
    four thousand files from ``docs/`` and none from ``src/``.

    Skips what ``list_dir`` skips, so what a search finds and what the tree shows are the
    same set of files, and an unreadable directory contributes nothing rather than raising.
    """
    found: list[str] = []
    queue = [root]
    while queue and len(found) < limit:
        current = queue.pop(0)
        for entry in list_dir(current):
            if entry.is_dir:
                queue.append(entry.path)
            elif len(found) < limit:
                found.append(entry.path)
    return found


def classify(path: str) -> str:
    """Whether this file can be opened, and if not, why.

    The NUL-byte test is the same heuristic ``git`` and ``grep`` use. It misfires on
    UTF-16, where every ASCII character carries a NUL, so the BOMs are checked first --
    without that, a UTF-16 source file reads as binary and cannot be opened at all.
    """
    try:
        size = os.path.getsize(path)
    except OSError:
        return MISSING
    if size > MAX_BYTES:
        return TOO_BIG
    try:
        with open(path, "rb") as handle:
            head = handle.read(SNIFF_BYTES)
    except OSError:
        return MISSING
    if head.startswith((codecs.BOM_UTF16_LE, codecs.BOM_UTF16_BE)):
        return TEXT
    return BINARY if b"\x00" in head else TEXT


#: Our own names for "this codec, with this byte order mark". Python has ``utf-8-sig``
#: and nothing equivalent for UTF-16: its ``utf-16`` codec strips a BOM of either order
#: on the way in and always writes the *platform's* order on the way out, so a
#: big-endian file loaded and saved unedited would come back byte-swapped. Carrying the
#: mark explicitly is what makes the round trip exact in both orders.
BOM_CODECS: dict[str, tuple[bytes, str]] = {
    "utf-16-le-sig": (codecs.BOM_UTF16_LE, "utf-16-le"),
    "utf-16-be-sig": (codecs.BOM_UTF16_BE, "utf-16-be"),
}

#: How an encoding is written in the pane footer.
ENCODING_LABELS = {"utf-8-sig": "utf-8 bom",
                   "utf-16-le-sig": "utf-16 le", "utf-16-be-sig": "utf-16 be"}


def encoding_label(encoding: str) -> str:
    return ENCODING_LABELS.get(encoding, encoding)


def decode(data: bytes) -> tuple[str, str]:
    """(text, encoding). The encoding is what :func:`encode` needs to reverse this."""
    if data.startswith(codecs.BOM_UTF8):
        return data.decode("utf-8-sig"), "utf-8-sig"
    for name, (bom, base) in BOM_CODECS.items():
        if data.startswith(bom):
            return data[len(bom):].decode(base), name
    try:
        return data.decode("utf-8"), "utf-8"
    except UnicodeDecodeError:
        pass
    # Not UTF-8 and nothing says what it is. cp1252 is the likely answer on this
    # platform; latin-1 is the guaranteed one -- it maps all 256 byte values, so it
    # cannot raise and cannot lose a byte on the way back. Mojibake that round-trips
    # beats a file that will not open.
    for encoding in ("cp1252", "latin-1"):
        try:
            return data.decode(encoding), encoding
        except UnicodeDecodeError:
            continue
    raise AssertionError("latin-1 decodes every byte")  # pragma: no cover


def detect_newline(text: str) -> str:
    """The dominant line ending, counted rather than assumed from the platform.

    LF for a file with no line ending at all: a new or single-line file in a repository
    is likelier to want LF than to want whatever Windows would have picked.
    """
    crlf = text.count("\r\n")
    lf = text.count("\n") - crlf
    cr = text.count("\r") - crlf
    if crlf and crlf >= lf and crlf >= cr:
        return "\r\n"
    if cr > lf:
        return "\r"
    return "\n"


@dataclass(frozen=True, slots=True)
class Loaded:
    """A file in memory, with everything needed to write it back as it was found.

    ``text`` holds LF only. ``newline`` is what the file had, and the save restores it.
    ``mtime_ns`` and ``size`` are the fingerprint the editor re-stats against to notice
    the file changing underneath it.
    """

    text: str
    encoding: str
    newline: str
    size: int
    mtime_ns: int


def load(path: str) -> Loaded:
    """Read a file into a buffer. Raises OSError if it cannot be read."""
    stat = os.stat(path)
    with open(path, "rb") as handle:
        data = handle.read()
    text, encoding = decode(data)
    newline = detect_newline(text)
    normalised = text.replace("\r\n", "\n").replace("\r", "\n")
    return Loaded(normalised, encoding, newline, stat.st_size, stat.st_mtime_ns)


def encode(text: str, encoding: str, newline: str) -> bytes:
    """Reverse :func:`load`'s decoding. LF in the buffer becomes the file's ending."""
    if newline != "\n":
        text = text.replace("\n", newline)
    if encoding in BOM_CODECS:
        bom, base = BOM_CODECS[encoding]
        return bom + text.encode(base)
    return text.encode(encoding)


def save(path: str, text: str, encoding: str, newline: str) -> Loaded:
    """Write the buffer out and return the fingerprint of what landed on disk.

    Written to a sibling temporary file and moved into place. A direct write that fails
    partway -- disk full, process killed, antivirus interrupting -- leaves the user's
    source truncated at whatever byte it reached, and the whole point of this module is
    that saving cannot damage a file.
    """
    data = encode(text, encoding, newline)
    folder = os.path.dirname(path) or "."
    temp = os.path.join(folder, f".{os.path.basename(path)}.asomedeck-tmp")
    try:
        with open(temp, "wb") as handle:
            handle.write(data)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(temp, path)
    except OSError:
        # Leave nothing behind on a failed save; the caller reports the original error.
        try:
            os.unlink(temp)
        except OSError:
            pass
        raise
    stat = os.stat(path)
    return Loaded(text, encoding, newline, stat.st_size, stat.st_mtime_ns)


def changed_on_disk(path: str, loaded: Loaded) -> bool:
    """Whether the file differs from the fingerprint taken when it was loaded.

    A deleted file counts as changed: the editor should say so rather than go on showing
    a buffer whose file is gone.
    """
    try:
        stat = os.stat(path)
    except OSError:
        return True
    return stat.st_mtime_ns != loaded.mtime_ns or stat.st_size != loaded.size


